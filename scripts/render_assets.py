def load_country_entries() -> list[dict]:
    """Top 20 countries by alive count from run-summary.json, with per-type
    counts taken from each country's published JSON (never hardcoded)."""
    summary = json.loads(
        (REPO / "data/out/run-summary.json").read_text(encoding="utf-8"))
    top = sorted(((c, n) for c, n in summary["by_country"].items()
                  if c != "unclassified"),
                 key=lambda kv: (-kv[1], kv[0]))[:20]
    entries = []
    for cc, count in top:
        records = json.loads(
            (REPO / f"data/out/by-country/{cc}.json").read_text(encoding="utf-8"))
        entries.append({
            "cc": cc,
            "name": ISO_NAMES.get(cc, cc),
            "count": count,
            "types": dict(collections.Counter(r["type"] for r in records)),
        })
    return entries


def fetch_flag(cc: str) -> str | None:
    """Flag PNG as a data URI. Local docs/flags/<cc>.png first (committed, no
    network in CI); flagcdn.com fallback for codes missing locally."""
    local = REPO / "docs/flags" / f"{cc.lower()}.png"
    if local.exists():
        data = local.read_bytes()
        if data:
            return base64.b64encode(data).decode("ascii")
    try:
        url = f"https://flagcdn.com/24x18/{cc.lower()}.png"
        with urllib.request.urlopen(url, timeout=15) as resp:
            data = resp.read()
        return base64.b64encode(data).decode("ascii") if data else None
    except OSError:
        return None  # card still renders, minus the flag


def card_country(t: str, cc: str, name: str, count: int, flag_b64: str | None,
                 rank: int, vmax: int) -> str:
    """One grid card in the Aurora system: flag, name, alive count, share bar."""
    W, H = 320, 150
    p = [D.card_open(t, W, H, D.brand_grad(t, f"bg-{t}"), rx=20)]
    if rank == 0:
        p.append(f'<rect x="1.25" y="1.25" width="{W - 2.5}" height="{H - 2.5}" '
                 f'rx="19" fill="none" stroke="url(#bg-{t})" stroke-width="2"/>')
    if flag_b64:
        p.append(f'<image x="22" y="22" width="44" height="33" '
                 f'href="data:image/png;base64,{flag_b64}"/>')
        p.append(f'<rect x="22" y="22" width="44" height="33" rx="4" '
                 f'fill="none" stroke="{D.HAIR[t]}" stroke-opacity="{D.HAIR_O[t]}" '
                 f'stroke-width="1"/>')
    else:
        p.append(f'<rect x="22" y="22" width="44" height="33" rx="6" '
                 f'fill="{D.HAIR[t]}" fill-opacity="{D.HAIR_O[t] * .6}"/>')
        p.append(D.mono(44, 43, cc, t, size=12, anchor="middle", color=D.TEXT[t]))
    display = name if len(name) <= 17 else name[:16] + "…"
    p.append(D.text_el(78, 42, display, 16, D.TEXT[t], weight=700))
    p.append(D.micro(78, 62, cc, t))
    p.append(D.ping(294, 28, D.GREEN[t], r=3.5))
    fill_fill = f"url(#bg-{t})" if rank == 0 else D.TEXT[t]
    p.append(D.text_el(22, 112, D.fmt(count), 34, fill_fill, weight=800))
    count_w = len(D.fmt(count)) * 34 * 0.60
    p.append(D.micro(22 + count_w + 12, 112, "alive", t))
    track_w = 130
    p.append(f'<rect x="22" y="126" width="{track_w}" height="5" rx="2.5" '
             f'fill="{D.HAIR[t]}" fill-opacity="{D.HAIR_O[t] * .8}"/>')
    share = max(count / vmax * track_w, 3)
    bar = f"url(#bg-{t})" if rank == 0 else D.ACC2[t]
    p.append(f'<rect x="22" y="126" width="{share:.1f}" height="5" rx="2.5" '
             f'fill="{bar}" opacity="{1.0 if rank == 0 else .75}" '
             f'class="gw" style="animation-delay:{.2 + rank * .05:.2f}s"/>')
    # one slow shimmer per card, staggered by rank so the grid shimmers in a wave
    p.append(f'<clipPath id="cc-{cc}-{t}"><rect x="1" y="1" width="{W - 2}" '
             f'height="{H - 2}" rx="19"/></clipPath>')
    p.append(f'<g clip-path="url(#cc-{cc}-{t})"><rect x="0" y="0" width="110" '
             f'height="{H}" fill="#FFFFFF" opacity="'
             f'{"0.09" if t == "dark" else "0.45"}" class="sw" '
             f'style="animation-delay:{rank * 0.45:.2f}s;'
             f'animation-duration:9s"/></g>')
    p.append("</svg>")
    return "\n".join(p)


def write_country_cards(entries: list[dict]) -> None:
    """Write country-<CC>.svg for both themes; remove stale country cards
    from countries that dropped out of the top 20."""
    flags = {e["cc"]: fetch_flag(e["cc"]) for e in entries}
    missing = [cc for cc, f in flags.items() if f is None]
    if missing:
        print(f"flag unavailable for {missing} — cards render with code badge")
    vmax = entries[0]["count"]
    for theme in ("light", "dark"):
        for i, e in enumerate(entries):
            out = ASSETS / theme / f"country-{e['cc']}.svg"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(
                card_country(theme, e["cc"], e["name"], e["count"],
                             flags[e["cc"]], i, vmax),
                encoding="utf-8")
        keep = {f"country-{e['cc']}.svg" for e in entries}
        for stale in ASSETS.glob(f"{theme}/country-*.svg"):
            if stale.name not in keep:
                stale.unlink()


def build_grid_block(entries: list[dict]) -> str:
    """HTML table: card image links to the combined per-country .txt; a closed
    <details> holds three per-type chips, zero-count types stay unlinked."""
    def cell(e: dict) -> str:
        chips = []
        for ptype in ("socks5", "socks4", "http"):
            n = e["types"].get(ptype, 0)
            if n:
                chips.append(f'<a href="{RAW_BASE}/by-country/{e["cc"]}/'
                             f'{ptype}.txt"><code>{ptype} · {n}</code></a>')
            else:
                chips.append(f'<code>{ptype} · 0</code>')
        alt = f"{e['name']} — {e['count']} alive proxies, plain-text list"
        return (
            f'<a href="{RAW_BASE}/by-country/{e["cc"]}.txt">'
            f'<picture><source media="(prefers-color-scheme: dark)" '
            f'srcset="assets/dark/country-{e["cc"]}.svg">'
            f'<img src="assets/light/country-{e["cc"]}.svg" alt="{alt}">'
            f'</picture></a>'
            f'<br><details><summary>socks5 · socks4 · http</summary>'
            f'{" · ".join(chips)}</details>'
        )

    rows = [entries[i:i + 4] for i in range(0, len(entries), 4)]
    body = "".join(
        "<tr>" + "".join(f"<td>{cell(e)}</td>" for e in row) + "</tr>\n"
        for row in rows)
    return f'<table>\n{body}</table>'


def update_readme_grid(entries: list[dict]) -> None:
    readme = README_PATH.read_text(encoding="utf-8")
    if GRID_START not in readme or GRID_END not in readme:
        print("country-grid markers missing from README — grid not updated")
        return
    start = readme.index(GRID_START) + len(GRID_START)
    end = readme.index(GRID_END)
    updated = (readme[:start] + "\n\n" + build_grid_block(entries) + "\n\n"
               + readme[end:])
    README_PATH.write_text(updated, encoding="utf-8")
    print(f"updated README country grid ({len(entries)} countries)")


