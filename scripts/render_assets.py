# live cards — regenerated by CI every run (numbers included)
CARDS = {
    "header": D.card_header,
    "stats": D.card_stats,
    "flow": D.card_flow,
    "tiers": D.card_tiers,
    "funnel": D.card_funnel,
    "countries": D.card_countries,
    "protocols": D.card_protocols,
    "architecture": D.card_architecture,
    "divider": D.card_divider,
    "footer": D.card_footer,
}

# motion cards — number-free brand art, deterministic output (never stale)
MOTION_CARDS = {
    "hero": D.card_hero_motion,
    "divider": D.card_divider,
    "footer": lambda t, d: D.card_footer(t),
}


def write_motion() -> None:
    for theme in ("light", "dark"):
        for name, fn in MOTION_CARDS.items():
            out = ASSETS / "motion" / theme / f"{name}.svg"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(fn(theme, {}), encoding="utf-8")
            print(f"wrote {out}")
    # v4 left a motion flow card behind; the live flow.svg (regenerated with
    # numbers + animation every run) replaces it
    stale = ASSETS / "motion"
    for theme in ("light", "dark"):
        old = stale / theme / "flow.svg"
        if old.exists():
            old.unlink()
            print(f"removed stale {old}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", default=None,
                        help="comma-separated live card names (default: all)")
    parser.add_argument("--motion", action="store_true",
                        help="write only the number-free motion set")
    args = parser.parse_args()

    if args.motion:
        write_motion()
        return 0

    data = load_real_data()
    names = [n.strip() for n in args.only.split(",")] if args.only else list(CARDS)
    unknown = [n for n in names if n not in CARDS]
    if unknown:
        parser.error(f"unknown card(s): {', '.join(unknown)}")
    for theme in ("light", "dark"):
        for name in names:
            out = ASSETS / theme / f"{name}.svg"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(CARDS[name](theme, data), encoding="utf-8")
            print(f"wrote {out}")
    # top-20 country fast-path cards + README grid (always derived from the
    # just-published run output; skipped with --only unless "countries" ran)
    if args.only is None or "countries" in names:
        entries = load_country_entries()
        write_country_cards(entries)
        update_readme_grid(entries)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
