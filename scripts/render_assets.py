#!/usr/bin/env python3
"""YUEL README asset generator (v6) — the "Aurora" animated brand set.

A complete visual redesign of the v5 editorial-minimal set. Same CI contract,
new visual language, and motion everywhere (see scripts/yuel_design.py for the
design system):

- every color still comes from assets/tokens.json — aubergine/cream surfaces,
  ONE brand gradient (ember -> coral -> magenta -> violet), green reserved for
  "alive"
- rich but brand-true animation: drifting aurora fields, marching-dash
  connectors, packets travelling the real pipeline paths (SMIL), ping rings,
  draw-in arcs and bars, shimmer sweeps, a typing terminal, one heartbeat
  numeral per card — all inside the SVG files, all disabled under
  ``prefers-reduced-motion``, all degrading to a complete static image
- the live cards (stats/flow/tiers/funnel/countries/protocols/architecture/
  country grid) are regenerated by CI on every 30-minute run from
  data/out/run-summary.json + data/out/all.json — the numbers never go stale
- the motion set (assets/motion/{light,dark}/hero|divider|footer.svg) is
  number-free brand art: it never changes, so CI does not need to commit it

Data handling is unchanged from v5: every number comes from the last real
pipeline run, protocol mix and score percentiles are derived from the
published all.json, and the generator asserts internal consistency.

Usage::

    python3 scripts/render_assets.py               # all live cards + grid + motion
    python3 scripts/render_assets.py --only stats  # subset of live cards
    python3 scripts/render_assets.py --motion      # motion set only

Output: assets/<light|dark>/<card>.svg, assets/motion/<light|dark>/*.svg,
and the README country-grid block between its markers.
"""

